const startBtn = document.getElementById("start-voice");
const textArea = document.getElementById("user-answer");

const SpeechRecognition = window.SpeechRecognition || window.webkitSpeechRecognition;
if (SpeechRecognition) {
    const recognition = new SpeechRecognition();
    recognition.lang = 'ja-JP';
    recognition.continuous = true;
    recognition.interimResults = true;

    let isRecording = false; 
    let finalTranscript = "";

    startBtn.addEventListener("click", function() {
        if (!isRecording) {
            finalTranscript = textArea.value; 
            recognition.start();
            isRecording = true;
            startBtn.innerText = "⏹ 録音を停止する";
        } else {
            recognition.stop();
            isRecording = false;
            startBtn.innerText = "🎤 音声入力スタート";
        }
    });

    recognition.onresult = function(event) {
        let interimTranscript = ""; 
        for (let i = event.resultIndex; i < event.results.length; i++) {
            if (event.results[i].isFinal) {
                finalTranscript += event.results[i][0].transcript;
            } else {
                interimTranscript += event.results[i][0].transcript;
            }
        }
        textArea.value = finalTranscript + interimTranscript;
    };

    recognition.onend = function() {
        isRecording = false;
        startBtn.innerText = "🎤 音声入力スタート";
    }
} else {
    startBtn.innerText = "お使いのブラウザは音声入力非対応です";
}

